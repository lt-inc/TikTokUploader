const button = document.querySelector('#send');
const result = document.querySelector('#result');
button.addEventListener('click', async () => {
  button.disabled = true;
  result.textContent = '';
  try {
    const server = new URL(document.querySelector('#server').value.trim());
    if (server.protocol !== 'https:' || server.hostname !== 'admin.legendary-trio.me' || server.username || server.password || server.search || server.hash) {
      throw new Error('Enter the HTTPS address of your Terex panel.');
    }
    const code = document.querySelector('#code').value.trim();
    if (code.length < 16 || code.length > 256) throw new Error('Paste the valid connection code generated by Terex.');
    const [tab] = await chrome.tabs.query({active: true, currentWindow: true});
    const current = new URL(tab?.url || '');
    if (current.protocol !== 'https:' || current.hostname !== 'www.tiktok.com') {
      throw new Error('Open www.tiktok.com in the active tab and sign in first.');
    }
    const approved = await chrome.permissions.request({origins: [`${server.origin}/*`]});
    if (!approved) throw new Error('Access to your Terex address was not granted.');
    const cookies = (await chrome.cookies.getAll({domain: 'tiktok.com'})).filter(cookie => {
      const domain = cookie.domain.replace(/^\./, '').toLowerCase();
      return domain === 'tiktok.com' || domain.endsWith('.tiktok.com');
    });
    if (!cookies.some(cookie => cookie.name === 'sessionid' && cookie.value)) {
      throw new Error('TikTok login is missing. Sign in and try again.');
    }
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 60000);
    let response;
    try {
      response = await fetch(`${server.origin}/api/tiktok/connect/payload`, {
        method: 'POST', credentials: 'omit', redirect: 'error', signal: controller.signal,
        headers: {'Content-Type': 'application/json'},
        body: JSON.stringify({pairing_token: code, cookies, user_agent: navigator.userAgent, origin: current.origin}),
      });
    } finally { clearTimeout(timeout); }
    const payload = await response.json();
    document.querySelector('#code').value = '';
    if (!response.ok) throw new Error(payload.error || payload.detail || 'Terex could not accept this connection.');
    if (payload.status === 'connected') {
      result.textContent = `Connected: @${payload.username}. Return to Terex and refresh the account.`;
    } else {
      result.textContent = 'Session received. Return to Terex and check the account or open browser verification.';
    }
  } catch (error) {
    result.textContent = error.name === 'AbortError'
      ? 'Connection response timed out. Check the account in Terex before generating a new code.'
      : error.message;
  } finally { button.disabled = false; }
});
